/**
 * HAProxy is two processes, not one: the proxy and the origin behind it. That makes
 * the ordering its own hazard -- an origin started after the proxy, or torn down
 * before it, turns every assertion in the row into a 503 -- and the pass-through of
 * trailers and chunked bodies is what the row exists to show, so it is checked here
 * as well as in the dimensions.
 */

const test = require("tape");

const net = require("node:net");
const { spawn } = require("node:child_process");

const { haproxyH1, haproxyH2, haproxyAvailable } = require("./haproxy.js");
const { waitForPort } = require("../../fixtures/net.js");
const { assertKnownCapabilities } = require("../capabilities.js");
const { PAYLOAD, TRAILER_NAME, TRAILER_VALUE } = require("../contract.js");
const { assertServesContract } = require("./contract-check.js");

const { Agent } = require("../../../index.js");
const { fetch } = require("../../../wrapper.js");

for (const server of [haproxyH1, haproxyH2]) {
	test(`haproxy: ${server.name} forwards to its origin`, async (t) => {
		assertKnownCapabilities(server.capabilities, `server ${server.name}`);

		if (!haproxyAvailable()) {
			t.pass("haproxy is not installed, so its configuration is unverified");
			t.end();
			return;
		}

		const running = await server.start();
		const agent = new Agent({
			tls: { extraRoots: [running.ca] },
			dns: { overrides: [{ domain: "localhost", addresses: ["127.0.0.1"] }] },
			http3: { upgradeEnabled: false },
		});

		try {
			const res = await fetch(`${running.url}/hello`, { agent, timeout: 10_000 });
			const body = await res.text();
			// 503 is the failure to look for: it means the proxy came up but its backend
			// did not, which is a fixture ordering bug rather than anything about faith.
			t.equal(res.status, 200, "the proxy reached its origin");
			t.equal(body, PAYLOAD, "and returned what the origin serves");
			t.equal(res.version, server.expectVersion, "over the protocol the row claims");

			// The pass-through this row exists for: a trailer generated by the origin,
			// arriving through a hop that had to re-emit it.
			const trailered = await fetch(`${running.url}/trailers`, { agent, timeout: 10_000 });
			await trailered.text();
			const trailers = await trailered.trailers;
			t.equal(
				trailers && trailers.get(TRAILER_NAME),
				TRAILER_VALUE,
				"a trailer survives the proxy hop",
			);

			await assertServesContract(t, {
				url: running.url,
				agent,
				capabilities: server.capabilities,
			});
		} finally {
			await running.close();
			t.end();
		}
	});
}

test("haproxy: an open port is not proof that this server opened it", async (t) => {
	// The bug this guards against was live for a while and failed about one run in
	// eight. findFreePort releases a port before handing it back, so the proxy's port
	// was unclaimed while the origin picked its own; when both landed on the same
	// number, the origin bound it, HAProxy could not, and readiness saw *a* listener
	// and said yes. Every request then went to the HTTP/1 origin behind the proxy,
	// which showed up as the row failing to negotiate HTTP/2.
	const squatter = net.createServer();
	await new Promise((resolve) => squatter.listen(0, "127.0.0.1", resolve));
	const { port } = squatter.address();

	// Two ways the timing can fall: the server is already gone when readiness starts,
	// or it dies while readiness is looking at a port someone else holds. Both are
	// asserted on the same property -- readiness reports the process, rather than
	// reporting success -- because which branch catches it is a race, and the property
	// is what matters.
	const scenarios = [
		{ what: "already gone", code: "process.exit(3)" },
		{ what: "dies while the port looks open", code: "setTimeout(() => process.exit(3), 30)" },
	];

	for (const { what, code } of scenarios) {
		const child = spawn(process.execPath, ["-e", code], { stdio: "ignore" });
		if (what === "already gone") await new Promise((resolve) => child.once("exit", resolve));

		try {
			await waitForPort({ port, describe: "stand-in", proc: child, timeoutMs: 2_000 });
			t.fail(`readiness accepted a port held by someone else (${what})`);
		} catch (err) {
			t.match(
				err.message,
				/stand-in exited with 3/,
				`readiness blames its own process rather than reporting ready (${what})`,
			);
		}
	}

	squatter.close();
	t.end();
});
