/**
 * Response trailers, and the ordering the fetch standard requires of them.
 *
 * Trailers only exist once a body has ended, so `response.trailers` does not resolve
 * until the body has been consumed — see https://github.com/whatwg/fetch/pull/1940.
 * That makes "await trailers, then read the body" a deadlock the caller wrote, which
 * is why the pending case is asserted here rather than smoothed over: the promise has
 * to stay cheap and cancellable while it waits, and it has to resolve the moment the
 * body ends.
 */

const test = require("tape");
const http = require("node:http");

const { Agent } = require("../index.js");
const { fetch } = require("../wrapper.js");

const PAYLOAD = "trailers-payload";
const TRAILER = "x-checksum";
const VALUE = "abc123";

/**
 * `/trailers` sends one, `/plain` sends none.
 *
 * Cleartext HTTP/1.1 deliberately: trailers have nothing to do with TLS, and the
 * shared test CA is generated by whichever openssl the platform ships -- which is a
 * source of failures of its own, since rustls rejected that certificate for its
 * extended key usage on macOS and Windows while accepting it on Linux. An OS-assigned
 * port, since there is no UDP listener to coordinate with here.
 */
async function origin() {
	const sockets = new Set();
	const server = http.createServer((req, res) => {
		res.setHeader("content-type", "text/plain");
		if (req.url === "/trailers") {
			res.setHeader("trailer", TRAILER);
			res.write(PAYLOAD);
			res.addTrailers({ [TRAILER]: VALUE });
			res.end();
			return;
		}
		res.end(PAYLOAD);
	});
	server.on("connection", (socket) => {
		sockets.add(socket);
		socket.on("close", () => sockets.delete(socket));
	});

	await new Promise((resolve, reject) => {
		server.once("error", reject);
		server.listen(0, "127.0.0.1", resolve);
	});

	return {
		url: `http://127.0.0.1:${server.address().port}`,
		agent: new Agent(),
		close: () =>
			new Promise((resolve) => {
				// The agent pools its connection, so a bare close() never settles.
				for (const socket of sockets) socket.destroy();
				sockets.clear();
				server.close(resolve);
				setTimeout(resolve, 500).unref();
			}),
	};
}

test("trailers: arrive once the body has been read", async (t) => {
	const server = await origin();
	try {
		const res = await fetch(`${server.url}/trailers`, { agent: server.agent, timeout: 10000 });
		t.equal(await res.text(), PAYLOAD, "the body reads back");

		const trailers = await res.trailers;
		t.ok(trailers, "and the trailers resolve");
		t.equal(trailers.get(TRAILER), VALUE, "carrying what the server sent");
	} finally {
		await server.close();
		t.end();
	}
});

test("trailers: a body with none resolves to null", async (t) => {
	const server = await origin();
	try {
		const res = await fetch(`${server.url}/plain`, { agent: server.agent, timeout: 10000 });
		await res.text();
		t.equal(
			await res.trailers,
			null,
			"null rather than an empty Headers, so a caller can tell none arrived",
		);
	} finally {
		await server.close();
		t.end();
	}
});

test("trailers: pending until the body is consumed, and idle while pending", async (t) => {
	const server = await origin();
	try {
		const res = await fetch(`${server.url}/trailers`, { agent: server.agent, timeout: 10000 });

		// Held, not awaited: awaiting here is the deadlock the standard describes.
		const pending = res.trailers;

		const raced = await Promise.race([
			pending.then(() => "resolved"),
			new Promise((resolve) => setTimeout(() => resolve("pending"), 500)),
		]);

		t.equal(
			raced,
			"pending",
			"does not resolve before the body is consumed, per the standard",
		);
		// That the wait is parked rather than a `yield_now` spin -- the bug this replaces --
		// is asserted in the Rust unit test `waiting_for_trailers_parks_rather_than_spinning`,
		// which counts wake-ups instead of sampling CPU. Timing the process measures the
		// machine as much as the code, and said more about how busy a CI runner was than
		// about whether the future parks.

		// And the same promise settles as soon as the body ends.
		t.equal(await res.text(), PAYLOAD, "the body is still there to read");
		const trailers = await pending;
		t.equal(
			trailers && trailers.get(TRAILER),
			VALUE,
			"the promise held from before the read resolves once the body ends",
		);
	} finally {
		await server.close();
		t.end();
	}
});

test("trailers: a discarded body settles them as none", async (t) => {
	const server = await origin();
	try {
		const res = await fetch(`${server.url}/trailers`, { agent: server.agent, timeout: 10000 });

		// Held first, so this also covers the case that used to wedge: a waiter already
		// parked when the body gets thrown away.
		const pending = res.trailers;
		await res.discard();

		t.equal(
			await pending,
			null,
			"discarding the body discards its trailers, rather than waiting for trailers " +
				"that can no longer arrive",
		);
		t.equal(await res.trailers, null, "and asking again says the same thing");
	} finally {
		await server.close();
		t.end();
	}
});
